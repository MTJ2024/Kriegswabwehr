-- Hauptfunktion: Missbrauchsbericht erstellen und via Discord versenden
-- Main function: create abuse report and send via Discord
function AbuseReporter.report(data)
    -- data = { ip, country, city, isp, asn, subnet, isVPN, isProxy, isHosting,
    --          attackType, violations, firstSeen, lastSeen, timestamps, action, subnetBlocked }

    data.refID = generateRefID(data.ip or "unknown")

    local dossier   = buildDossier(data)
    local arfReport = buildARFReport(data)

    -- Konsolenausgabe / Console output
    Logger.warn("[ABUSE-REPORT] Generiert für / Generated for IP=" .. (data.ip or "?") .. " Ref=" .. data.refID)
    print(dossier)

    -- An Discord senden (als langer Embed + Datei) / Send to Discord (as long embed + file)
    if Config.DiscordWebhook and Config.DiscordWebhook ~= "" then
        -- Dossier-Kurzfassung als Embed / Short dossier as embed
        Logger.sendDiscord(
            "📁 Beweisdossier / Evidence Dossier – " .. data.refID,
            "```\n" .. dossier:sub(1, 3800) .. "\n```",
            Config.DiscordColors.permban,
            {
                { name = "🌐 IP",            value = data.ip or "?",          inline = true  },
                { name = "🗺️ Land",          value = data.country or "?",     inline = true  },
                { name = "🏢 ISP",           value = data.isp or "?",         inline = true  },
                { name = "📋 Ref-ID",        value = data.refID,              inline = true  },
                { name = "⚔️ Angriffstyp",  value = data.attackType or "?",  inline = true  },
                { name = "🔢 Verstöße",      value = tostring(data.violations or 0), inline = true },
                { name = "📨 ARF-Bericht",   value = "Im nächsten Embed / In next embed", inline = false },
            }
        )

        -- ARF-Bericht als separater Embed / ARF report as separate embed
        Wait(500)
        Logger.sendDiscord(
            "📨 RFC-5965-ARF-Missbrauchsbericht / Abuse Report – " .. data.refID,
            "Bitte an **abuse@" .. (data.isp or "isp.example"):lower():gsub("%s+", "") .. "** weiterleiten:\n```\n" .. arfReport:sub(1, 3500) .. "\n```",
            Config.DiscordColors.warning,
            {
                { name = "📬 Senden an / Send to", value = "abuse@" .. (data.isp or "?"):lower():gsub("[^a-z0-9%-%.]+", ""), inline = false },
            }
        )
    end

    return data.refID
end

-- Schnellbericht bei Stufe-3-Eskalation / Quick report on level-3 escalation
function AbuseReporter.quickReport(ip, geoData, violations)
    local geo = geoData or {}
    AbuseReporter.report({
        ip           = ip,
        country      = geo.country or "XX",
        city         = geo.city or "Unknown",
        isp          = geo.isp or "Unknown",
        asn          = geo.asn or "Unknown",
        subnet       = (geo.ip and geo.ip:match("^(%d+%.%d+%.%d+)") or ip:match("^(%d+%.%d+%.%d+)") or "?") .. ".0/24",
        isVPN        = geo.isVPN or false,
        isProxy      = geo.isProxy or false,
        isHosting    = geo.isHosting or false,
        attackType   = "DDoS / Connection Flood (Loading Screen Phase)",
        violations   = violations or 3,
        firstSeen    = os.time(),
        lastSeen     = os.time(),
        action       = "permban + subnet block",
        subnetBlocked = true,
    })
end

